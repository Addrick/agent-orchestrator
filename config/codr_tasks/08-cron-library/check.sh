def _alarm(*_):
    raise Timeout()


signal.signal(signal.SIGALRM, _alarm)
groups = {}


def case(group, fn, seconds=5):
    ok = False
    signal.alarm(seconds)
    try:
        ok = fn() is True
    except BaseException:  # noqa: BLE001 - any error, a timeout included, fails the case
        ok = False
    finally:
        signal.alarm(0)
    g = groups.setdefault(group, [0, 0])
    g[0] += ok
    g[1] += 1


def raises(expr):
    try:
        cronlib.parse(expr)
    except cronlib.CronError:
        return True
    return False


